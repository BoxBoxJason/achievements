/**
 * Generates the reference pages of the documentation site from their source of truth:
 * - docs/content/docs/commands.md and settings.md from the package.json contributions,
 * - docs/content/docs/achievements.md from the achievement stacking templates.
 *
 * Usage: ts-node scripts/generate-docs.ts [--check]
 * With --check, nothing is written and the process fails when a committed page is stale.
 *
 * @author BoxBoxJason
 */

import fs from "node:fs";
import path from "node:path";
import { StackingTemplates } from "../src/database/model/init/StackingTemplates";
import { StackingAchievementTemplate } from "../src/database/model/tables/Achievement";

const ROOT = path.resolve(__dirname, "..");
const PAGES_DIR = path.join(ROOT, "docs", "content", "docs");
const GENERATED_NOTICE =
  "<!-- Code generated by scripts/generate-docs.ts (run `npm run docs:generate`); DO NOT EDIT. -->";

interface Command {
  command: string;
  title: string;
}

interface Setting {
  type: string;
  default?: unknown;
  description?: string;
  enum?: string[];
}

interface PackageJson {
  contributes: {
    commands: Command[];
    configuration: { properties: Record<string, Setting> }[];
  };
}

const numberFormat = new Intl.NumberFormat("en-US");

/** Escapes a value for a Markdown table cell. */
function cell(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function code(value: string): string {
  return "`" + value + "`";
}

function page(title: string, weight: number, description: string, intro: string, body: string): string {
  return `---\ntitle: ${title}\nweight: ${weight}\ndescription: ${JSON.stringify(description)}\n---\n\n${GENERATED_NOTICE}\n\n${intro}\n\n${body.trimEnd()}\n`;
}

function commandsPage(pkg: PackageJson): string {
  const rows = pkg.contributes.commands.map(
    ({ command, title }) => `| **${cell(title)}** | ${code(command)} |`,
  );

  return page(
    "Commands",
    50,
    "Every command of the Achievements extension for VS Code, with its identifier, to run from the Command Palette or bind to a shortcut.",
    "Run these commands from the Command Palette (`Ctrl+Shift+P` / `Cmd+Shift+P`), or bind them to keyboard shortcuts.",
    ["| Command | Identifier |", "| ------- | ---------- |", ...rows].join("\n"),
  );
}

function formatDefault(value: unknown): string {
  if (Array.isArray(value)) {
    return value.length === 0 ? "`[]`" : value.map((item) => code(String(item))).join(", ");
  }
  if (value === undefined) {
    return "";
  }
  return value === "" ? '`""`' : code(String(value));
}

function settingsPage(pkg: PackageJson): string {
  const rows = pkg.contributes.configuration.flatMap((section) =>
    Object.entries(section.properties).map(([name, setting]) => {
      let description = setting.description ?? "";
      if (setting.enum) {
        description += ` One of ${setting.enum.map(code).join(", ")}.`;
      }
      return `| ${code(name)} | ${setting.type} | ${formatDefault(setting.default)} | ${cell(description.trim())} |`;
    }),
  );

  return page(
    "Settings",
    60,
    "Every setting of the Achievements extension for VS Code: type, default value and effect, from tracked events to logging and the status bar.",
    'Open **File > Preferences > Settings** and search for "Achievements", or run **Achievements: Settings**.',
    ["| Setting | Type | Default | Description |", "| ------- | ---- | ------- | ----------- |", ...rows].join("\n"),
  );
}

/** The language a per-language template variant is about, read from its criteria name suffix. */
function variantLanguage(template: StackingAchievementTemplate): string {
  const criteria = template.criterias[0];
  return criteria.slice(criteria.lastIndexOf("_") + 1);
}

/** Replaces the criteria names of a description with N (or N1, N2, ... when there are several). */
function genericDescription(template: StackingAchievementTemplate): string {
  return template.criterias.reduce(
    (description, criteria, index) =>
      description.replace(criteria, template.criterias.length === 1 ? "N" : `N${index + 1}`),
    template.description,
  );
}

function thresholds(template: StackingAchievementTemplate): string {
  const tiers = template.maxTier - template.minTier + 1;
  const first = template.criteriasFunctions[0](template.minTier);
  const last = template.criteriasFunctions[0](template.maxTier);
  const range = tiers === 1 ? numberFormat.format(first) : `${numberFormat.format(first)} → ${numberFormat.format(last)}`;
  return `${range} (${tiers} ${tiers === 1 ? "tier" : "tiers"})`;
}

function titles(title: string, template: StackingAchievementTemplate): string {
  const tiers = template.maxTier - template.minTier + 1;
  if (!title.includes("%d")) {
    return title;
  }
  return tiers === 1 ? title.replace("%d", "1") : `${title.replace("%d", "1")} … ${title.replace("%d", String(tiers))}`;
}

function achievementRows(templates: StackingAchievementTemplate[], languages: Set<string>): string[] {
  return templates
    .filter((template) => !template.hidden)
    .map((template) => {
      let title = template.title;
      let description = genericDescription(template);
      if (template.criterias[0].includes("_")) {
        const language = variantLanguage(template);
        languages.add(language);
        // Whole words only: the "r" language must not match the "r" of "Write".
        const word = new RegExp(`(?<![\\w#+-])${language.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}(?![\\w#+-])`);
        title = title.replace(word, "`<language>`");
        description = description.replace(word, "`<language>`");
      }
      return `| ${cell(titles(title, template))} | ${cell(template.group)} | ${cell(description)} | ${thresholds(template)} |`;
    });
}

function achievementsPage(): string {
  // Same categories, in the same order, as the database initialization (src/database/model/init/init.ts).
  const categories: [string, Record<string, unknown>][] = [
    ["Productivity", StackingTemplates.productivity],
    ["Git", StackingTemplates.git],
    ["VS Code", StackingTemplates.vscode],
    ["Files", StackingTemplates.files],
  ];
  const languages = new Set<string>();
  const sections: string[] = [];

  for (const [name, namespace] of categories) {
    const rows: string[] = [];
    for (const factory of Object.values(namespace)) {
      if (typeof factory !== "function") {
        continue;
      }
      const result = (factory as () => StackingAchievementTemplate | StackingAchievementTemplate[])();
      const templates = Array.isArray(result) ? result : [result];
      // Per-language variants only differ by their language: keep one row for all of them.
      const unique = new Map<string, string>();
      for (const row of achievementRows(templates, languages)) {
        unique.set(row, row);
      }
      rows.push(...unique.values());
    }
    sections.push(
      `## ${name}\n\n| Achievements | Group | Requirement | Required N |\n| ------------ | ----- | ----------- | ---------- |\n${rows.join("\n")}`,
    );
  }

  const intro = [
    "Every achievement comes in tiers: each tier raises the required value N, and earns more experience.",
    "",
    `Rows with \`<language>\` exist once per tracked language: ${[...languages].sort().map(code).join(", ")}.`,
  ].join("\n");

  return page(
    "Achievements",
    40,
    "The full catalogue of achievements you can unlock in VS Code, with their tiers, requirements and the values needed for each tier.",
    intro,
    sections.join("\n\n"),
  );
}

function main(): void {
  const check = process.argv.includes("--check");
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8")) as PackageJson;
  const pages: Record<string, string> = {
    "commands.md": commandsPage(pkg),
    "settings.md": settingsPage(pkg),
    "achievements.md": achievementsPage(),
  };

  const stale: string[] = [];
  for (const [file, content] of Object.entries(pages)) {
    const target = path.join(PAGES_DIR, file);
    if (check) {
      const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
      if (current !== content) {
        stale.push(path.relative(ROOT, target));
      }
    } else {
      fs.mkdirSync(PAGES_DIR, { recursive: true });
      fs.writeFileSync(target, content);
    }
  }

  if (stale.length > 0) {
    console.error(`Stale documentation pages: ${stale.join(", ")}. Run \`npm run docs:generate\` and commit the result.`);
    process.exit(1);
  }
}

main();
